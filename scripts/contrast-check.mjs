// WCAG contrast check for the colour tokens in src/styles/tokens/colors.css.
// Parses the light, dark and ink-band blocks, checks every text/background pair
// we actually use, writes docs/CONTRAST.md, and exits 1 if anything fails.
// Usage: node scripts/contrast-check.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync("src/styles/tokens/colors.css", "utf8");

function block(name) {
  const m = css.match(new RegExp(`/\\* @${name}:start \\*/([\\s\\S]*?)/\\* @${name}:end \\*/`));
  if (!m) throw new Error(`Missing block ${name}`);
  const vars = {};
  for (const [, k, v] of m[1].matchAll(/--c-([a-z0-9-]+):\s*(#[0-9a-f]{6})/gi)) vars[k] = v;
  return vars;
}

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (h) => {
  const [r, g, b] = hex(h).map(lin);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [l1, l2] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
};

// [foreground, background, minimum, usage]
const pairs = [
  ["ink", "bg", 4.5, "Body text on page"],
  ["ink", "surface", 4.5, "Body text on cards"],
  ["ink", "sunken", 4.5, "Body text on alternate bands"],
  ["muted", "bg", 4.5, "Secondary text on page"],
  ["muted", "surface", 4.5, "Secondary text on cards"],
  ["muted", "sunken", 4.5, "Secondary text on alternate bands"],
  ["accent-text", "bg", 4.5, "Eyebrows, accent words, numbers"],
  ["accent-text", "surface", 4.5, "Accent text on cards"],
  ["accent-text", "sunken", 4.5, "Accent text on alternate bands"],
  ["accent-2", "bg", 4.5, "Links in prose"],
  ["on-accent", "accent", 4.5, "Text on marigold buttons/tags"],
  ["bg", "ink", 4.5, "Primary button text"],
  ["on-whatsapp", "whatsapp", 4.5, "WhatsApp button text"],
  ["success", "surface", 3, "Success icons (non-text, 3:1)"],
  ["error", "surface", 4.5, "Error messages"],
  ["error", "bg", 4.5, "Error messages on page"],
  ["line-strong", "surface", 3, "Form field borders (non-text, 3:1)"],
  ["focus", "bg", 3, "Focus ring (non-text, 3:1)"],
  ["accent", "bg", 3, "Marigold fills as UI (non-text, 3:1)"],
];

const themes = { Light: block("theme-light"), Dark: block("theme-dark"), "Ink band": block("band-ink") };
const lines = ["# Contrast report", "", "Generated by `npm run check:contrast` from `src/styles/tokens/colors.css`. WCAG 2.1 AA: 4.5:1 for text, 3:1 for large text and UI.", ""];
let failures = 0;

for (const [name, t] of Object.entries(themes)) {
  lines.push(`## ${name}`, "", "| Foreground | Background | Ratio | Needs | Result | Used for |", "|---|---|---|---|---|---|");
  for (const [fg, bg, min, use] of pairs) {
    // The marigold fill is decorative next to text in the light theme (never text on paper).
    if (name === "Light" && fg === "accent" && bg === "bg") continue;
    if (!t[fg] || !t[bg]) continue;
    const r = ratio(t[fg], t[bg]);
    const ok = r >= min;
    if (!ok) failures++;
    lines.push(`| \`${fg}\` ${t[fg]} | \`${bg}\` ${t[bg]} | ${r.toFixed(2)} | ${min} | ${ok ? "Pass" : "**FAIL**"} | ${use} |`);
  }
  lines.push("");
}
lines.push(
  "Notes",
  "",
  "- In the light theme, marigold (`accent`) is only used as a fill behind ink text, or as a decorative mark next to text. Marigold text on paper uses `accent-text`.",
  "- `line` is a decorative hairline and is not required to meet 3:1. Form borders use `line-strong`.",
  "",
);
writeFileSync("docs/CONTRAST.md", lines.join("\n"));
console.log(lines.filter((l) => l.startsWith("|") || l.startsWith("##")).join("\n"));
console.log(failures ? `\n${failures} pair(s) fail` : "\nAll pairs pass WCAG AA");
process.exit(failures ? 1 : 0);
